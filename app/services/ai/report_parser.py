# Слова из работы, которые Whisper иначе путает: подсказка распознаванию речи (initial_prompt) — ускоряет и улучшает узнавание.
ASR_PROMPT = (
    "Итог выезда монтёра на комплекс видеофиксации АПК. Проверка пинга, питание, СЭС, электросеть, блок питания, аккумулятор, роутер, "
    "SIM-карта, камера, регистратор, кронштейн, шкаф, кабель, обжим, оптоволокно, автовышка, лестница, замена, перезагрузка, неисправность."
)

SCHEMA = {
    "type": "object",
    "properties": {
        "done": {"type": "string"}, "cause": {"type": "string"}, "needs": {"type": "string"},
        "fixed": {"type": "string", "enum": ["да", "нет", "неизвестно"]},
    },
    "required": ["done", "cause", "needs", "fixed"], "additionalProperties": False,
}

SYSTEM = """Ты помощник диспетчера. Монтёр наговорил голосом итог выезда на комплекс видеофиксации (АПК). Тебе дают расшифровку речи — в ней бывают ошибки распознавания, повторы и разговорные слова. Разложи сказанное по полям:

done — что было сделано: действия по порядку, кратко, деловым языком, 1–3 предложения (например: «Заменён блок питания, перезагружен роутер, проверена связь»).
cause — причина неисправности или то, что обнаружено неисправным, если монтёр это назвал или оно очевидно из слов (например: «Сгорел блок питания», «Обрыв кабеля», «SIM-карта не регистрируется в сети»). Если причина не названа или выезд не по ремонту — пустая строка.
needs — что нужно для восстановления или продолжения работ, если исправить не удалось или чего-то не хватило: запчасти, оборудование, инструмент, доступ, согласование, особый способ работы (например: «Нужна автовышка — на лестницу не подняться», «Требуется новый блок питания 12 В», «Нужен ключ от шкафа»). Свободный текст своими словами по смыслу. Если ничего не нужно — пустая строка.
fixed — «да», если комплекс заработал или неисправность устранена; «нет», если не заработал или работа не завершена; «неизвестно», если из слов не ясно.

Правила: используй только то, что сказано; ничего не придумывай и не добавляй. Слова «нужно / нужна / надо / требуется / не хватило / ждём» описывают то, что ещё НУЖНО, а не сделано: это только в needs, а в done такое как выполненное не писать (в done — лишь действия, названные в прошедшем времени: «заменили», «перезагрузили», «осмотрели»; если ничего не сделано — «Осмотр комплекса; устранить неисправность не удалось.»). Исправляй очевидные ошибки распознавания по смыслу работы, но не меняй смысл. Слова: АПК/комплекс — комплекс видеофиксации; СЭС — солнечная электростанция; БП — блок питания; пинг — проверка связи; автовышка — подъёмник вместо лестницы. Если сказанное не про выезд (шум, «алло, не слышно»), в done напиши, что речь не распознана."""

