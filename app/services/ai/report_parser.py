def _clean(value: Any, limit: int = 700) -> str:
    text = " ".join(str(value or "").split())
    if text.lower().strip(" .") in ("", "нет", "не указано", "не названо", "none", "null", "-", "—", "неизвестно", "не требуется", "ничего"):
        return ""
    return text[:limit]


def _messages_history() -> list[dict]:
    import json

    history: list[dict] = []
    for question, answer in EXAMPLES:
        history.append({"role": "user", "content": question})
        history.append({"role": "assistant", "content": json.dumps(answer, ensure_ascii=False)})
    return history


async def parse(transcript: str, *, visit_type: str = "", point_id: str = "", priority: int = client.PRIORITY_BOT) -> dict[str, Any]:
    """Расшифровка → {"done","cause","needs","fixed","used_ai"}. Модель недоступна — весь текст как «что сделано» (used_ai=False)."""
    text = " ".join((transcript or "").split())
    fallback = {"done": text, "cause": "", "needs": "", "fixed": "неизвестно", "used_ai": False}
    if len(text) < 6:
        return fallback
    user = f"Тип выезда: {visit_type or 'не указан'}.\n" + (f"Комплекс: {point_id}.\n" if point_id else "") + f"Расшифровка: «{text}»"
    try:
        data = await client.llm_json(SYSTEM, user, SCHEMA, schema_name="voice_report", max_tokens=450, priority=priority, history=_messages_history())
    except (client.AiUnavailable, client.AiError) as exc:
        logger.warning("Разбор голосового итога не удался: %s", exc)
        fallback["error"] = str(exc)
        return fallback
    done = _clean(data.get("done"), 900) or text
    fixed = data.get("fixed") if data.get("fixed") in ("да", "нет", "неизвестно") else "неизвестно"
    return {"done": done, "cause": _clean(data.get("cause")), "needs": _clean(data.get("needs")), "fixed": fixed, "used_ai": True}
