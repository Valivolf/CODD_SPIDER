"""Голосовой итог монтёра → поля отчёта. Расшифровка речи (client.transcribe) отдаётся языковой модели, которая делит текст на:
  done  — что было сделано (итог работ);
  cause — в чём была причина неисправности (если это ремонт и причина названа);
  needs — что нужно для восстановления, если исправить не удалось (запчасти, автовышка вместо лестницы, доступ — свободный текст);
  fixed — устранена ли неисправность (да / нет / неизвестно) — подсказка для итога, сам итог выбирает монтёр.
Модель только раскладывает сказанное по полям и поправляет явные ошибки распознавания речи; придумывать новое ей запрещено."""
from __future__ import annotations

