def sim_key_valid(key: str) -> bool:
    """Похоже ли это на настоящий номер SIM: только цифры, не короче 5. «-», «нет», «0» и подобные заглушки в поле
    «Номер SIM» комплекса в учёт оборудования не попадают (иначе десятки комплексов схлопнулись бы в одну «SIM»)."""
    return key.isdigit() and len(key) >= 5


def sim_key(value) -> str:
    """Серийный номер SIM-карты в системе: последние 7 цифр длинного номера с карты (так хранится points.sim_number и
    ключ реестра SIM↔IP). Если цифр нет — номер как есть."""
    text = str(value or "").strip()
    digits = "".join(c for c in text if c.isdigit())
    return digits[-7:] if digits else text

