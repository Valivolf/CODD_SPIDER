"""Состояние текущего диалога с монтёром — только в памяти процесса.

Бот больше не хранит ничего в БД (ни своей, ни через lan_calendar) для
навигации: сценарий линейный (меню → список заданий → пошаговый опрос по
заданию), явного стека "назад" через произвольные экраны не нужно — каждый
шаг сам знает, куда вести дальше. Если бот перезапустится посреди диалога,
монтёр просто начинает заново — то же ограничение, что было в исходной
версии бота у её in-memory `_active_sessions`, только теперь это
единственный источник состояния, а не запасной вариант поверх БД."""

_sessions: dict[int, dict] = {}


def get_session(vk_id: int) -> dict:
    return _sessions.setdefault(vk_id, {})


def reset_session(vk_id: int) -> None:
    _sessions[vk_id] = {}
